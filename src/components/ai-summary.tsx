"use client";

import { useState } from "react";
import { useCompletion } from "@ai-sdk/react";

/**
 * "Analyze with AI" panel. The server does the heavy lifting (/api/analyze);
 * this component only starts the request and renders the text as it streams in.
 */
export function AiSummary({ username }: { username: string }) {
  const [emptyResult, setEmptyResult] = useState(false);
  const { completion, complete, isLoading, error, stop } = useCompletion({
    api: "/api/analyze",
    // Separate state per user; without an id every profile would share one analysis.
    id: `analysis-${username.toLowerCase()}`,
    body: { username },
    throttle: 50,
    // The model can finish without writing anything (e.g. a safety filter); say so instead of showing nothing.
    onFinish: (_prompt, result) => setEmptyResult(result.trim().length === 0),
  });

  function analyze() {
    setEmptyResult(false);
    void complete("");
  }

  const hasResult = completion.length > 0;

  return (
    <section
      aria-labelledby="ai-heading"
      className="window p-6" data-tone="lilac"
    >
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h2 id="ai-heading" className="text-2xl">
            AI profile analysis
          </h2>
          <p className="text-sm text-zinc-500">A short summary of skills, projects and activity, written by AI.</p>
        </div>

        {isLoading ? (
          <button type="button" onClick={stop} className={secondaryButton}>
            Stop
          </button>
        ) : (
          <button type="button" onClick={analyze} className={primaryButton}>
            {hasResult ? "Regenerate" : "✨ Analyze with AI"}
          </button>
        )}
      </div>

      {error && (
        <p role="alert" className="mt-4 text-sm text-red-600">
          {error.message || "Something went wrong. Please try again."}
        </p>
      )}

      {emptyResult && !isLoading && !error && (
        <p role="alert" className="mt-4 text-sm text-amber-700">
          The AI finished without returning any text. Please try again.
        </p>
      )}

      {isLoading && !hasResult && (
        <div className="mt-5 animate-pulse space-y-2" aria-label="Generating analysis">
          <div className="h-4 w-1/3 rounded bg-zinc-200" />
          <div className="h-3 w-full rounded bg-zinc-100" />
          <div className="h-3 w-5/6 rounded bg-zinc-100" />
        </div>
      )}

      {hasResult && (
        <div className="mt-5" aria-live="polite" aria-busy={isLoading}>
          <AnalysisText text={completion} />
          <p className="mt-4 text-xs text-zinc-500">
            Generated by AI from public GitHub data. It can make mistakes.
          </p>
        </div>
      )}
    </section>
  );
}

/**
 * Renders the small subset of markdown the prompt asks for ("## " headings, "- " bullets).
 * Built from plain React elements, so model output can never inject HTML.
 */
function AnalysisText({ text }: { text: string }) {
  const blocks: { heading: string | null; items: string[] }[] = [];

  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith("#")) {
      blocks.push({ heading: line.replace(/^#+\s*/, ""), items: [] });
      continue;
    }
    if (blocks.length === 0) blocks.push({ heading: null, items: [] });
    blocks[blocks.length - 1].items.push(line.replace(/^[-*•]\s*/, "").replaceAll("**", ""));
  }

  return (
    <div className="grid gap-5 sm:grid-cols-2">
      {blocks.map((block, i) => (
        <div key={i}>
          {block.heading && <h3 className="mb-1.5 font-semibold">{block.heading}</h3>}
          <ul className="list-disc space-y-1 pl-5 text-sm text-zinc-700">
            {block.items.map((item, j) => (
              <li key={j}>{item}</li>
            ))}
          </ul>
        </div>
      ))}
    </div>
  );
}

const primaryButton =
  "btn px-4 py-2 text-sm";
const secondaryButton =
  "btn btn-quiet px-4 py-2 text-sm";
